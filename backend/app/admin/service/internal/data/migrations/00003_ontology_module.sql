CREATE TABLE public.ont_ontologies (
    id bigint NOT NULL,
    created_at timestamp with time zone,
    updated_at timestamp with time zone,
    deleted_at timestamp with time zone,
    created_by bigint,
    updated_by bigint,
    deleted_by bigint,
    is_enabled boolean DEFAULT true,
    ontology_name character varying,
    ontology_iri character varying,
    base_iri character varying,
    description character varying DEFAULT ''::character varying,
    version bigint DEFAULT 0
);
ALTER TABLE public.ont_ontologies ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.ont_ontologies_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1);
ALTER TABLE ONLY public.ont_ontologies
    ADD CONSTRAINT ont_ontologies_pkey PRIMARY KEY (id);
CREATE INDEX idx_ont_ontologies_ontology_name ON public.ont_ontologies USING btree (ontology_name);
CREATE UNIQUE INDEX uix_ont_ontologies_iri ON public.ont_ontologies USING btree (ontology_iri) WHERE (deleted_at IS NULL);

