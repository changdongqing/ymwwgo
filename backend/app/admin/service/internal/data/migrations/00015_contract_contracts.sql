-- 合同底座三表（独立 Go module go-wind-admin/contract）
-- 设计: docs/connn/contract-type-and-contract-design.md §4（统一合同底座：生命周期
-- 状态机 + 类型快照 + 版本链；费用明细子表 = 拆解生成的应收/应付/押金行；事件
-- 子表 = 追加不变时间线）。
-- 来源: 按 ent schema（backend/contract/data/ent/schema/contract*.go）整理。
-- 禁止修改本文件；后续变更一律新增 000NN_contract_<what>.sql。
-- 合同号不带独立序列：contract_no = 'CT-' + 8 位零填自增 id（同事务派生），
-- 与工单号同法（业务序列会让漂移守卫永远红）。
-- 列 COMMENT 与 ent schema 的 Comment 逐字一致（漂移守卫比对注释文本）。

