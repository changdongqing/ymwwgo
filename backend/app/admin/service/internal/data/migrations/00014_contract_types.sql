CREATE TABLE public.contract_types (
    id bigint NOT NULL,
    created_at timestamp with time zone,
    updated_at timestamp with time zone,
    deleted_at timestamp with time zone,
    created_by bigint,
    updated_by bigint,
    deleted_by bigint,
    is_enabled boolean DEFAULT true,
    code character varying,
    name character varying,
    level character varying,
    description character varying DEFAULT ''::character varying,
    party_b_label character varying,
    pay_method character varying,
    pay_nodes jsonb,
    fee_direction character varying,
    requires_approval boolean,
    requires_deposit boolean,
    diff_fields jsonb,
    required_attachments jsonb,
    guidance character varying,
    parent_id bigint
);

ALTER TABLE public.contract_types ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.contract_types_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.contract_types
    ADD CONSTRAINT contract_types_pkey PRIMARY KEY (id);

CREATE UNIQUE INDEX contract_types_code_key ON public.contract_types USING btree (code);

CREATE INDEX contracttype_parent_id ON public.contract_types USING btree (parent_id);

CREATE INDEX contracttype_level ON public.contract_types USING btree (level);

ALTER TABLE ONLY public.contract_types
    ADD CONSTRAINT contract_types_contract_types_children FOREIGN KEY (parent_id) REFERENCES public.contract_types(id) ON DELETE SET NULL;

