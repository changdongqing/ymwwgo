COMMENT ON COLUMN public.onestop_periodic_plans.tenant_id IS '租户ID';

CREATE INDEX periodicplan_tenant_id ON public.onestop_periodic_plans USING btree (tenant_id);

ALTER TABLE public.onestop_transport_routes
