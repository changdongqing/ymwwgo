COMMENT ON COLUMN public.onestop_transport_routes.tenant_id IS '租户ID';

CREATE INDEX transportroute_tenant_id ON public.onestop_transport_routes USING btree (tenant_id);

-- 4) 工单表：主表（三形态共用 + 快照 + SLA deadline）+ 执行项子表（计划任务
--    逐项记录）+ 事件子表（时间线/跟进流程）。工单号不带独立序列：order_no =
--    'WO-' + 8 位零填自增 id（同事务派生），单调性与全局序列等价，且不引入
--    ent 之外的结构对象（漂移守卫是严格 diff，业务序列会永远红）。

