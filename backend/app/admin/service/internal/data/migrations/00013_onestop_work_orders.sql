-- 一站式统一工单底座（docs/yizhanshi/onestop-unified-work-order.md，P2a）。
--
-- 1) onestop_service_types 加列 order_kind：履约形态（细类回退小类，两级都空
--    按 0106 子树/计划生成/事件顺序推导）；存量库按矩阵回填被服收发（010405）
--    显式覆写为运送形态（与种子同口径，守卫测试三处同步）。
-- 2) onestop_periodic_plans / onestop_transport_routes 补挂租户列：工单是租户
--    业务数据，生单来源必须先归属租户。0 = 平台（内置模板/平台自身业务），
--    可空带默认值与主仓既有租户列口径一致；租户可见性由 TenantID mixin 的
--    租户 Privacy 承担（本迁移不回填——dev 实测零租户，无默认租户可指）。
-- 3) 三张工单表：主表（三形态共用 + 快照 + SLA deadline）+ 执行项子表（计划
--    任务逐项记录）+ 事件子表（时间线/跟进流程）；工单号序列。
-- 列 COMMENT 与 ent schema 的 Comment 逐字一致（漂移守卫比对注释文本）。

-- +goose Up

-- 1) 履约形态列
ALTER TABLE public.onestop_service_types
    ADD COLUMN IF NOT EXISTS order_kind character varying;

COMMENT ON COLUMN public.onestop_service_types.order_kind IS '履约形态 KIND_EVENT:事件处置 KIND_TASK:计划任务 KIND_TRANSPORT:运送（未设置回退上级；两级都空按 0106 子树/计划生成/事件顺序推导）';

-- 2) 存量库覆写回填：被服收发按业务形状（收送交接）归运送形态
UPDATE public.onestop_service_types SET order_kind = 'KIND_TRANSPORT'
 WHERE code LIKE '010405%';

-- 3) 计划/路线租户化
ALTER TABLE public.onestop_periodic_plans
