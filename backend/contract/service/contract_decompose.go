package service

import (
	"fmt"
	"time"

	"github.com/tx7do/go-utils/trans"
	"google.golang.org/protobuf/types/known/timestamppb"

	contractV1 "go-wind-admin/contract/api/gen/go/contract/service/v1"
)

// 费用拆解器（纯函数，docs/connn/contract-type-and-contract-design.md §6）。
//
// 输入：合同生效时快照（金额/保证金/付款方式/费用方向/起止日期）+ 解析后的
// 付款节点模板；输出费用行集。金额计算以分（int64）为单位消除浮点误差，
// 等分行余数进最后一行（Σ行金额 == 合同金额，分毫不差）。
// 生成时机：合同生效（Approve，或 requires_approval=false 的 Submit）；
// 「重新拆解」删自动行后重跑（手工行保留）。

const (
	feeNameContract = "合同款"
	feeNameDeposit  = "履约保证金"
)

// DecomposeInput 拆解输入（合同生效快照）。
type DecomposeInput struct {
	Amount       float64                       // 合同金额（元）
	Deposit      float64                       // 履约保证金（元；>0 即拆押金行）
	PayMethod    contractV1.PayMethod          // 付款方式快照
	FeeDirection contractV1.FeeDirection       // 费用方向（应收/应付）
	StartDate    time.Time                     // 合同开始日期（日期语义）
	EndDate      time.Time                     // 合同结束日期（日期语义）
	PayNodes     []*contractV1.ContractPayNode // 付款节点模板（解析后）
}

// roundCent 元 → 分（四舍五入）。
func roundCent(v float64) int64 {
	if v >= 0 {
		return int64(v*100 + 0.5)
	}
	return int64(v*100 - 0.5)
}

// centToYuan 分 → 元。
func centToYuan(c int64) float64 {
	return float64(c) / 100
}

// contractCategory 费用方向 → 费用类别（应付=费用，应收=收入）。
func contractCategory(direction contractV1.FeeDirection) contractV1.FeeCategory {
	if direction == contractV1.FeeDirection_DIRECTION_RECEIVABLE {
		return contractV1.FeeCategory_CATEGORY_INCOME
	}
	return contractV1.FeeCategory_CATEGORY_EXPENSE
}

// lastDayOfMonth 目标月最后一天（按月推进时截"日"用：1/31 + 1月 = 2/28|29，
// 不用 time.AddDate——它把越界日规整到下月初，语义错误）。
func addMonthsClamped(base time.Time, months int) time.Time {
	y, m, d := base.Date()
	totalMonths := int(m) - 1 + months
	ty, tm := y+totalMonths/12, time.Month(totalMonths%12+1)
	// 目标月天数
	nextMonth := time.Date(ty, tm+1, 1, 0, 0, 0, 0, base.Location()).AddDate(0, 0, -1)
	maxDay := nextMonth.Day()
	if d > maxDay {
		d = maxDay
	}
	return time.Date(ty, tm, d, base.Hour(), base.Minute(), base.Second(), base.Nanosecond(), base.Location())
}

// installmentDates 起止日期按 stepMonths 切期：从 start 起每 stepMonths 一期，
// 直至超出 end；至少 1 期（end 早于 start 时也只出 1 期）。
// 每期都从 start 推算（i×step）而非从上一期累加——月末截断会丢失原始"日"
//（1/31→2/28 后再 +1 月会得 3/28 而非 3/31）。
func installmentDates(start, end time.Time, stepMonths int) []time.Time {
	dates := []time.Time{start}
	for i := 1; ; i++ {
		next := addMonthsClamped(start, i*stepMonths)
		if next.After(end) {
			break
		}
		dates = append(dates, next)
	}
	return dates
}

// DecomposeContractFees 拆解合同金额为费用行集（纯函数）。
// 返回行均为 autoGenerated=true、status=FEE_STATUS_PENDING。
func DecomposeContractFees(in DecomposeInput) []*contractV1.ContractFee {
	direction := in.FeeDirection
	if direction == contractV1.FeeDirection_DIRECTION_UNSPECIFIED {
		direction = contractV1.FeeDirection_DIRECTION_PAYABLE
	}
	category := contractCategory(direction)

	var fees []*contractV1.ContractFee
	appendRow := func(name string, amountCents int64, planDate *time.Time) {
		fee := &contractV1.ContractFee{
			Name:          trans.Ptr(name),
			Category:      category.Enum(),
			Direction:     direction.Enum(),
			Status:        contractV1.FeeStatus_FEE_STATUS_PENDING.Enum(),
			Amount:        trans.Ptr(centToYuan(amountCents)),
			AutoGenerated: trans.Ptr(true),
		}
		if planDate != nil {
			fee.PlanDate = timestamppb.New(*planDate)
		}
		fees = append(fees, fee)
	}

	totalCents := roundCent(in.Amount)
	switch in.PayMethod {
	case contractV1.PayMethod_PAY_MONTHLY, contractV1.PayMethod_PAY_QUARTERLY:
		step := 3
		nameFmt := "第%d期"
		if in.PayMethod == contractV1.PayMethod_PAY_MONTHLY {
			step = 1
			nameFmt = "%d月服务费"
		}
		dates := installmentDates(in.StartDate, in.EndDate, step)
		if len(dates) == 0 {
			break
		}
		per := totalCents / int64(len(dates))
		remainder := totalCents - per*int64(len(dates))
		for i, d := range dates {
			amountCents := per
			if i == len(dates)-1 {
				amountCents += remainder // 余数进最后一期：Σ行 == 总额
			}
			appendRow(fmt.Sprintf(nameFmt, i+1), amountCents, &d)
		}

	case contractV1.PayMethod_PAY_NODE, contractV1.PayMethod_PAY_PROGRESS:
		if len(in.PayNodes) == 0 {
			// 无节点模板：退化为一次性全额（计划日期空，履约时补）
			appendRow(feeNameContract, totalCents, nil)
			break
		}
		perNodes := make([]int64, len(in.PayNodes))
		allocated := int64(0)
		for i, node := range in.PayNodes {
			perNodes[i] = totalCents * int64(node.GetRatioPercent()) / 100
			allocated += perNodes[i]
		}
		perNodes[len(perNodes)-1] += totalCents - allocated // 比例取整误差进末节点
		for i, node := range in.PayNodes {
			appendRow(node.GetName(), perNodes[i], nil) // 节点付款行计划日期空，履约时补
		}

	default: // PAY_ONCE / UNSPECIFIED：一次性全额
		start := in.StartDate
		appendRow(feeNameContract, totalCents, &start)
	}

	// 押金行：方向随合同（我方付押金=应付；收对方押金=应收）
	if roundCent(in.Deposit) > 0 {
		start := in.StartDate
		fees = append(fees, &contractV1.ContractFee{
			Name:          trans.Ptr(feeNameDeposit),
			Category:      contractV1.FeeCategory_CATEGORY_DEPOSIT.Enum(),
			Direction:     direction.Enum(),
			Status:        contractV1.FeeStatus_FEE_STATUS_PENDING.Enum(),
			Amount:        trans.Ptr(in.Deposit),
			PlanDate:      timestamppb.New(start),
			AutoGenerated: trans.Ptr(true),
		})
	}

	return fees
}
