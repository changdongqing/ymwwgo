func TestDecomposeDepositRow(t *testing.T) {
	// 押金行：随合同方向（应收=收对方押金），计划日期=开始日期
	fees := DecomposeContractFees(DecomposeInput{
		Amount:       36000,
		Deposit:      5000,
		PayMethod:    contractV1.PayMethod_PAY_MONTHLY,
		FeeDirection: contractV1.FeeDirection_DIRECTION_RECEIVABLE,
		StartDate:    mustDay(t, "2026-01-01"),
		EndDate:      mustDay(t, "2026-03-31"),
	})
	if len(fees) != 4 {
		t.Fatalf("rows = %d, want 3 期月租 + 1 押金", len(fees))
	}
	last := fees[len(fees)-1]
	if last.GetName() != "履约保证金" || last.GetCategory() != contractV1.FeeCategory_CATEGORY_DEPOSIT {
		t.Errorf("last = %s/%s, want 履约保证金/DEPOSIT", last.GetName(), last.GetCategory())
	}
	if last.GetDirection() != contractV1.FeeDirection_DIRECTION_RECEIVABLE {
		t.Errorf("押金方向 = %s, want 随合同 RECEIVABLE", last.GetDirection())
	}
	if roundCent(last.GetAmount()) != 500000 {
		t.Errorf("押金金额 = %d cents, want 500000", roundCent(last.GetAmount()))
	}
}

