// 费用拆解纯函数守卫：钉死设计 §6 的拆解口径——
// 一次性/按月等分与余数/按季/节点比例与取整误差/押金行/月末截断。
// 任何一侧改动都会在这里红。

func mustDay(t *testing.T, s string) time.Time {
	t.Helper()
	d, err := time.ParseInLocation("2006-01-02", s, time.Local)
	if err != nil {
		t.Fatalf("parse date %q: %v", s, err)
	}
	return d
}

func sumFees(fees []*contractV1.ContractFee) int64 {
	total := int64(0)
	for _, fee := range fees {
		total += roundCent(fee.GetAmount())
	}
	return total
}

func TestDecomposeOnce(t *testing.T) {
	fees := DecomposeContractFees(DecomposeInput{
		Amount:       100000.01,
		PayMethod:    contractV1.PayMethod_PAY_ONCE,
		FeeDirection: contractV1.FeeDirection_DIRECTION_PAYABLE,
		StartDate:    mustDay(t, "2026-01-01"),
		EndDate:      mustDay(t, "2026-12-31"),
	})
	if len(fees) != 1 {
		t.Fatalf("rows = %d, want 1", len(fees))
	}
	if fees[0].GetName() != "合同款" || fees[0].GetCategory() != contractV1.FeeCategory_CATEGORY_EXPENSE {
		t.Errorf("row0 = %s/%s, want 合同款/EXPENSE", fees[0].GetName(), fees[0].GetCategory())
	}
	if got := roundCent(fees[0].GetAmount()); got != 10000001 {
		t.Errorf("amount = %d cents, want 10000001", got)
	}
	if !fees[0].GetPlanDate().AsTime().Equal(mustDay(t, "2026-01-01")) {
		t.Errorf("planDate = %v, want 2026-01-01", fees[0].GetPlanDate().AsTime())
	}
	if !fees[0].GetAutoGenerated() || fees[0].GetStatus() != contractV1.FeeStatus_FEE_STATUS_PENDING {
		t.Errorf("autoGenerated/status 不符")
	}
}

func TestDecomposeMonthlyEvenSplitAndRemainder(t *testing.T) {
	// 12 个月 10000.00 元：每月 833.33，末月 833.37（余数进末行，Σ==总额）
	fees := DecomposeContractFees(DecomposeInput{
		Amount:       10000,
		PayMethod:    contractV1.PayMethod_PAY_MONTHLY,
		FeeDirection: contractV1.FeeDirection_DIRECTION_PAYABLE,
		StartDate:    mustDay(t, "2026-01-05"),
		EndDate:      mustDay(t, "2026-12-31"),
	})
	if len(fees) != 12 {
		t.Fatalf("rows = %d, want 12", len(fees))
	}
	if sumFees(fees) != 1000000 {
		t.Errorf("sum = %d cents, want 1000000", sumFees(fees))
	}
	if r := roundCent(fees[0].GetAmount()); r != 83333 {
		t.Errorf("row0 = %d cents, want 83333", r)
	}
	if r := roundCent(fees[11].GetAmount()); r != 83337 {
		t.Errorf("row11 = %d cents, want 83337（余数进末行）", r)
	}
	if !fees[0].GetPlanDate().AsTime().Equal(mustDay(t, "2026-01-05")) {
		t.Errorf("row0 planDate = %v, want 每月同日 2026-01-05", fees[0].GetPlanDate().AsTime())
	}
}

func TestDecomposeMonthlyClampsMonthEnd(t *testing.T) {
	// 1/31 起租至 4/30：期次日期须为 1/31、2/28（2026 非闰年）、3/31、4/30——
	// time.AddDate 会把 1/31+1月 规整成 3/3，这里钉死"日截断到月末"口径
	dates := installmentDates(mustDay(t, "2026-01-31"), mustDay(t, "2026-04-30"), 1)
	want := []string{"2026-01-31", "2026-02-28", "2026-03-31", "2026-04-30"}
	if len(dates) != len(want) {
		t.Fatalf("dates = %v, want %v", dates, want)
	}
	for i, d := range dates {
		if got := d.Format("2006-01-02"); got != want[i] {
			t.Errorf("dates[%d] = %s, want %s", i, got, want[i])
		}
	}
}

