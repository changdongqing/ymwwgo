func TestDecomposePayNodes(t *testing.T) {
	// 施工：基础30/主体40/竣工25/质保5，100 万 → 30/40/25/5 万整
	fees := DecomposeContractFees(DecomposeInput{
		Amount:       1000000,
		PayMethod:    contractV1.PayMethod_PAY_NODE,
		FeeDirection: contractV1.FeeDirection_DIRECTION_PAYABLE,
		StartDate:    mustDay(t, "2026-03-01"),
		EndDate:      mustDay(t, "2026-12-31"),
		PayNodes: []*contractV1.ContractPayNode{
			{Name: "基础", RatioPercent: 30},
			{Name: "主体", RatioPercent: 40},
			{Name: "竣工", RatioPercent: 25},
			{Name: "质保", RatioPercent: 5},
		},
	})
	if len(fees) != 4 {
		t.Fatalf("rows = %d, want 4", len(fees))
	}
	wantAmounts := []int64{30000000, 40000000, 25000000, 5000000}
	for i, fee := range fees {
		if got := roundCent(fee.GetAmount()); got != wantAmounts[i] {
			t.Errorf("row%d = %d cents, want %d", i, got, wantAmounts[i])
		}
		if fee.GetPlanDate() != nil {
			t.Errorf("row%d 节点付款行计划日期须为空（履约时补）", i)
		}
	}
	if sumFees(fees) != 100000000 {
		t.Errorf("sum = %d cents, want 100000000", sumFees(fees))
	}
}

func TestDecomposePayNodesRoundingTolerance(t *testing.T) {
	// 三节点 1/3×3：33/33/34（取整误差进末节点，Σ==总额）
	fees := DecomposeContractFees(DecomposeInput{
		Amount:       100,
		PayMethod:    contractV1.PayMethod_PAY_PROGRESS,
		FeeDirection: contractV1.FeeDirection_DIRECTION_RECEIVABLE,
		StartDate:    mustDay(t, "2026-01-01"),
		EndDate:      mustDay(t, "2026-06-30"),
		PayNodes: []*contractV1.ContractPayNode{
			{Name: "预付", RatioPercent: 33},
			{Name: "到货", RatioPercent: 33},
			{Name: "验收", RatioPercent: 34},
		},
	})
	if len(fees) != 3 {
		t.Fatalf("rows = %d, want 3", len(fees))
	}
	if sumFees(fees) != 10000 {
		t.Errorf("sum = %d cents, want 10000", sumFees(fees))
	}
	// 应收方向 → 收入类别
	if fees[0].GetCategory() != contractV1.FeeCategory_CATEGORY_INCOME {
		t.Errorf("category = %s, want INCOME（应收）", fees[0].GetCategory())
	}
}

